// The simulation is intentionally independent of the DOM and persistence layer.
import { advanceViral, canTransmit, createViralState, validViralState } from "./viral.js";

export const SAVE_VERSION = 2;
export const MAX_OFFLINE_SECONDS = 6 * 60 * 60;
export const TAKEOVER_TO_BUILD = 0.7;
export const TAKEOVER_TO_LAUNCH = 0.95;

const PLANETS = [
  { name: "Hespera", epithet: "The orchard world", population: 1500, vigilance: 0.08, description: "They are many. You are one borrowed body. Begin quietly." },
  { name: "Koru", epithet: "The watchful cities", population: 2200, vigilance: 0.2, description: "Their sentries notice patterns. Break their trust before their defenses." },
  { name: "Vey", epithet: "The ocean of towers", population: 3200, vigilance: 0.32, description: "A world joined by signals. Its network will become yours." },
  { name: "Orison", epithet: "The frozen citadel", population: 4500, vigilance: 0.43, description: "Their final sanctuaries stand against the tide of bodies." }
];

export const UPGRADES = [
  { id: "spores", name: "Viral Shedding", description: "Infected carriers transmit more efficiently without manual orders.", baseCost: 16, costScale: 1.85 },
  { id: "vectors", name: "Whisper Network", description: "Infected hosts quietly recruit others.", baseCost: 35, costScale: 1.95 },
  { id: "digesters", name: "Biomass Reclaimers", description: "Extract more biomass from the occupied world.", baseCost: 65, costScale: 1.9 },
  { id: "mimicry", name: "Perfected Disguise", description: "Reduce the vigilance drawn by new conversions.", baseCost: 140, costScale: 2.1 }
];

export const GENES = [
  { id: "seed", name: "Inherited Hosts", description: "+2 starting hosts on every future world per rank.", unlockAfterWorlds: 0 },
  { id: "whisper", name: "Hive Resonance", description: "+25% passive assimilation on all future worlds per rank.", unlockAfterWorlds: 0 },
  { id: "hunger", name: "Adaptive Digestion", description: "+25% biomass production on all future worlds per rank.", unlockAfterWorlds: 0 },
  { id: "mimic", name: "Mimetic Memory", description: "Less vigilance generated by assimilation per rank.", unlockAfterWorlds: 1 },
  { id: "rupture", name: "Contagious Legacy", description: "+20% passive spread on future worlds per rank.", unlockAfterWorlds: 2 },
  { id: "archive", name: "Neural Archive", description: "Begin future worlds with a Whisper Network rank per gene rank.", unlockAfterWorlds: 3 }
];

export const DIRECTIVES = [
  { id: "seedfall", name: "Mass Seedfall", description: "Start the next world with twelve additional hosts.", unlockAfterWorlds: 0 },
  { id: "cache", name: "Smuggled Biomass", description: "Start the next world with 100 biomass.", unlockAfterWorlds: 0 },
  { id: "veil", name: "Deep Cover", description: "Your next invasion spreads 20% faster and draws half as much vigilance.", unlockAfterWorlds: 0 },
  { id: "siege", name: "Siege Organism", description: "Start with a spore and network upgrade, but with 25 vigilance.", unlockAfterWorlds: 2 }
];

function geneRank(state, id) {
  return Math.max(0, Number(state.lineage.genes[id]) || 0);
}

function clone(state) {
  return {
    ...state,
    upgrades: { ...state.upgrades },
    lineage: { worlds: state.lineage.worlds, genes: { ...state.lineage.genes } }
  };
}

export function getPlanet(state) {
  const template = PLANETS[state.planetIndex % PLANETS.length];
  const cycles = Math.floor(state.planetIndex / PLANETS.length);
  return {
    ...template,
    name: cycles === 0 ? template.name : template.name + " " + (cycles + 1),
    population: Math.round(template.population * Math.pow(1.33, state.planetIndex)),
    vigilance: Math.min(0.8, template.vigilance + cycles * 0.045)
  };
}

export function createGame(now = Date.now(), planetIndex = 0, lineage = { worlds: 0, genes: {} }, directive = "pioneer") {
  const genes = { ...lineage.genes };
  const state = {
    version: SAVE_VERSION,
    planetIndex,
    stage: planetIndex === 0 && lineage.worlds === 0 ? "viral" : "planetary",
    viral: planetIndex === 0 && lineage.worlds === 0 ? createViralState() : null,
    hosts: 1 + 2 * (Number(genes.seed) || 0) + (directive === "seedfall" ? 12 : 0),
    biomass: directive === "cache" ? 100 : 0,
    vigilance: directive === "siege" ? 25 : 0,
    upgrades: {
      spores: directive === "siege" ? 1 : 0,
      vectors: (Number(genes.archive) || 0) + (directive === "siege" ? 1 : 0),
      digesters: 0,
      mimicry: 0
    },
    launcherBuilt: false,
    directive,
    lineage: { worlds: lineage.worlds, genes },
    updatedAt: now
  };
  state.hosts = Math.min(state.hosts, getPlanet(state).population);
  return state;
}

export function takeover(state) {
  return Math.min(1, state.hosts / getPlanet(state).population);
}

export function getStats(state) {
  const planet = getPlanet(state);
  const freeHosts = Math.max(0, planet.population - state.hosts);
  const vigilancePenalty = Math.max(0.2, 1 - state.vigilance / 135 - planet.vigilance * 0.35);
  const directiveBoost = state.directive === "veil" ? 1.2 : 1;
  const spreadPerSecond = freeHosts <= 0 ? 0 :
    (state.hosts * 0.045 + state.upgrades.vectors * 1.2) *
    (1 + geneRank(state, "whisper") * 0.25) *
    (1 + state.upgrades.spores * 0.3 + geneRank(state, "rupture") * 0.2) *
    directiveBoost * vigilancePenalty;
  return {
    spreadPerSecond: Math.min(freeHosts, spreadPerSecond),
    biomassPerSecond: (state.hosts * 0.09 + state.upgrades.digesters * 1.1) *
      (1 + geneRank(state, "hunger") * 0.25),
    vigilanceMultiplier: Math.max(0.1, (1 - geneRank(state, "mimic") * 0.15) *
      (state.directive === "veil" ? 0.5 : 1))
  };
}

export function beginTransmission(state) {
  if (state.stage !== "viral" || !canTransmit(state.viral)) return state;
  return { ...clone(state), stage: "planetary", viral: null };
}

export function advance(state, seconds) {
  const next = clone(state);
  if (!Number.isFinite(seconds) || seconds <= 0) return next;
  if (next.stage === "viral") {
    next.viral = advanceViral(next.viral, seconds);
    return next;
  }
  const planet = getPlanet(next);
  let left = Math.min(seconds, MAX_OFFLINE_SECONDS);
  while (left > 0) {
    const step = Math.min(1, left);
    const stats = getStats(next);
    const captured = Math.min(Math.max(0, planet.population - next.hosts), stats.spreadPerSecond * step);
    next.biomass += stats.biomassPerSecond * step;
    next.hosts += captured;
    next.vigilance = Math.max(0, Math.min(100,
      next.vigilance + (captured / planet.population * 48 * stats.vigilanceMultiplier) -
      step * (0.012 + next.upgrades.mimicry * 0.045)
    ));
    left -= step;
  }
  return next;
}

export function upgradeCost(state, id) {
  const upgrade = UPGRADES.find(item => item.id === id);
  if (!upgrade) return Infinity;
  return Math.ceil(upgrade.baseCost * Math.pow(upgrade.costScale, state.upgrades[id]) *
    Math.pow(1.22, state.planetIndex));
}

export function buyUpgrade(state, id) {
  if (!Object.prototype.hasOwnProperty.call(state.upgrades, id)) return state;
  const cost = upgradeCost(state, id);
  if (state.biomass < cost) return state;
  const next = clone(state);
  next.biomass -= cost;
  next.upgrades[id] += 1;
  return next;
}

export function launcherCost(state) {
  return Math.ceil(850 * Math.pow(1.3, state.planetIndex));
}

export function buildLauncher(state) {
  if (state.launcherBuilt || takeover(state) < TAKEOVER_TO_BUILD || state.biomass < launcherCost(state)) return state;
  const next = clone(state);
  next.biomass -= launcherCost(next);
  next.launcherBuilt = true;
  return next;
}

export function canLaunch(state) {
  return state.launcherBuilt && takeover(state) >= TAKEOVER_TO_LAUNCH;
}

export function availableGenes(state) {
  return GENES.filter(gene => state.lineage.worlds >= gene.unlockAfterWorlds);
}

export function availableDirectives(state) {
  return DIRECTIVES.filter(directive => state.lineage.worlds >= directive.unlockAfterWorlds);
}

export function launchScout(state, geneId, directiveId, now = Date.now()) {
  if (!canLaunch(state) ||
      !availableGenes(state).some(gene => gene.id === geneId) ||
      !availableDirectives(state).some(directive => directive.id === directiveId)) return state;
  const lineage = {
    worlds: state.lineage.worlds + 1,
    genes: { ...state.lineage.genes, [geneId]: geneRank(state, geneId) + 1 }
  };
  return createGame(now, state.planetIndex + 1, lineage, directiveId);
}

function validCore(candidate) {
  if (!candidate || typeof candidate !== "object" ||
      !Number.isInteger(candidate.planetIndex) || candidate.planetIndex < 0 || candidate.planetIndex > 400 ||
      !Number.isFinite(candidate.hosts) || candidate.hosts < 1 ||
      !Number.isFinite(candidate.biomass) || candidate.biomass < 0 ||
      !Number.isFinite(candidate.vigilance) || candidate.vigilance < 0 || candidate.vigilance > 100 ||
      typeof candidate.launcherBuilt !== "boolean" ||
      !Number.isFinite(candidate.updatedAt) ||
      !candidate.upgrades || !candidate.lineage || !candidate.lineage.genes ||
      !Number.isInteger(candidate.lineage.worlds) || candidate.lineage.worlds < 0 ||
      typeof candidate.directive !== "string") return false;
  return UPGRADES.every(upgrade => Number.isInteger(candidate.upgrades[upgrade.id]) &&
    candidate.upgrades[upgrade.id] >= 0 && candidate.upgrades[upgrade.id] <= 1000) &&
    Object.values(candidate.lineage.genes).every(value => Number.isInteger(value) && value >= 0 && value <= 1000);
}

export function validSave(candidate) {
  if (!validCore(candidate) || candidate.version !== SAVE_VERSION) return false;
  if (candidate.stage === "viral") {
    return candidate.planetIndex === 0 && candidate.lineage.worlds === 0 &&
      candidate.hosts === 1 && validViralState(candidate.viral);
  }
  return candidate.stage === "planetary" && candidate.viral === null;
}

export function migrateLegacyGame(candidate) {
  if (!validCore(candidate) || candidate.version !== 1) return null;
  return { ...candidate, version: SAVE_VERSION, stage: "planetary", viral: null };
}
